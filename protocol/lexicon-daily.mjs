const best = new Map()
const missing = new Set()
const oversized = new Set()

function add(word, pinyin, freq) {
  const chars = Array.from(word)
  const syls = pinyin.split(' ').filter(Boolean)
  if (chars.length !== syls.length) throw new Error(`${word} 字数 ${chars.length} 和拼音 ${syls.length} 不一致`)
  if (chars.length < 2) return
  if (chars.length > 16) { oversized.add(word); return }
  for (const syl of syls) {
    if (!SYLLABLES.has(syl)) throw new Error(`${word} 里有不能用的音节 ${syl}`)
  }
  const prev = best.get(word)
  if (prev && prev[1] !== pinyin) throw new Error(`${word} 的拼音冲突：${prev[1]} / ${pinyin}`)
  if (!prev || freq > prev[2]) best.set(word, [word, pinyin, freq])
}

function line(freq, ...parts) {
  const syls = []
  for (const part of parts) {
    const py = W[part]
    if (!py) {
      missing.add(part)
      return
    }
    syls.push(py)
  }
  add(parts.join(''), syls.join(' '), freq)
}

