const best = new Map()
const next = new Map()

function pinyinOf(parts) {
  const syls = []
  for (const part of parts) {
    const py = W[part]
    if (!py) throw new Error(`口语层缺拼音：${part}`)
    for (const syl of py.split(' ')) {
      if (!SYLLABLES.has(syl)) throw new Error(`${part} 的音节 ${syl} 不合法`)
      syls.push(syl)
    }
  }
  return syls
}

function add(freq, ...parts) {
  const word = parts.join('')
  const chars = Array.from(word)
  if (chars.length < 2 || chars.length > 8) return
  const syls = pinyinOf(parts)
  if (syls.length !== chars.length) throw new Error(`${word} 字数和音节数不一致`)
  const pinyin = syls.join(' ')
  const prev = best.get(word)
  if (prev && prev[1] !== pinyin) throw new Error(`${word} 的拼音冲突：${prev[1]} / ${pinyin}`)
  if (!prev || freq > prev[2]) best.set(word, [word, pinyin, freq])
  for (let i = 0; i + 1 < parts.length; i++) follow(parts[i], parts[i + 1])
}

function follow(prev, word) {
  let list = next.get(prev)
  if (!list) {
    list = []
    next.set(prev, list)
  }
  if (!list.includes(word) && list.length < 16) list.push(word)
}

